/// One badge entry in the picker (`525104`: `unlockedBadges` / `lockedBadges`).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
struct PickerBadge {
    id: u64,
    pack_name: Option<&'static str>,
}

/// Splits the base badges and pack badges into unlocked and locked lists (`525104`).
fn badge_collection(features: &[String]) -> (Vec<PickerBadge>, Vec<PickerBadge>) {
    let mut unlocked: Vec<PickerBadge> = BADGE_IDS
        .iter()
        .copied()
        .map(|id| PickerBadge {
            id,
            pack_name: None,
        })
        .collect();
    let mut locked = Vec::new();
    for &(feature, pack_name, ids) in BADGE_PACKS {
        let owned = features.iter().any(|known| known == feature);
        let target = if owned { &mut unlocked } else { &mut locked };
        for &id in ids {
            target.push(PickerBadge {
                id,
                pack_name: Some(pack_name),
            });
        }
    }
    (unlocked, locked)
}
