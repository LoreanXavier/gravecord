    /// The page (`NX`).
    pub(super) fn server_tag_page(&self, guild: Id, cx: &mut Context<Self>) -> AnyElement {
        let Some(state) = self.server_settings.as_ref().map(|open| &open.tag) else {
            return div().into_any_element();
        };
        let has_tags = self
            .stores
            .guild(guild)
            .is_some_and(|known| known.features.iter().any(|feature| feature == "GUILD_TAGS"));
        let turned_on = state.now.tag.is_some();
        let enabled = has_tags && turned_on;
        // `Nf.i.VISIBLE`: public, and public while recruiting.
        let public = matches!(state.visibility, 1 | 3);
        let error = state.error.clone();
        use super::server_settings::Page;
        // Two links in one sentence: each opens its page.
        let before = "Create a tag that your server members can display next to their name! Anyone outside your server can view your ";
        let first = "Server Profile";
        let middle = " through the Server Tag, and if applications are enabled, they can ";
        let second = "apply to join";
        let text = format!("{before}{first}{middle}{second}.");
        let first_range = before.len()..before.len() + first.len();
        let second_start = first_range.end + middle.len();
        let second_range = second_start..second_start + second.len();
        let link = gpui::HighlightStyle {
            color: Some(color("--text-link").into()),
            ..Default::default()
        };
        let root = cx.entity().downgrade();
        let description = gpui::InteractiveText::new(
            "tag-description",
            gpui::StyledText::new(text)
                .with_highlights([(first_range.clone(), link), (second_range.clone(), link)]),
        )
        .on_click(vec![first_range, second_range], move |at, _, cx| {
            let _ = root.update(cx, |this, cx| {
                this.go_to_page(if at == 0 { Page::Profile } else { Page::Access }, cx);
            });
        });
        let edit_setting = self.text_with_link(
            "tag-edit-setting",
            "Your Server Profile is private. Users will not be able to see it from a Server Tag. ",
            "Edit Setting",
            "",
            cx,
            |this, cx| this.go_to_page(Page::Profile, cx),
        );
        let top_control: AnyElement = if has_tags {
            div()
                .p(px(12.))
                .rounded(px(4.))
                .bg(color("--background-base-lower"))
                .flex()
                .items_center()
                .justify_between()
                .child(
                    div()
                        .text_size(px(16.))
                        .line_height(px(20.))
                        .font_weight(FontWeight(600.))
                        .text_color(color("--text-strong"))
                        .child("Enable Server Tag"),
                )
                .child(
                    div()
                        .id("tag-enable")
                        .cursor_pointer()
                        .child(super::create_channel::switch(turned_on))
                        .on_click(cx.listener(|this, _, _, cx| {
                            if let Some(state) = this.tag_mut() {
                                state.now.tag = if state.now.tag.is_some() {
                                    None
                                } else {
                                    Some(String::new())
                                };
                            }
                            cx.notify();
                        })),
                )
                .into_any_element()
        } else {
            div()
                .id("tag-unlock")
                .w(px(202.))
                .h(px(40.))
                .pl(px(16.))
                .rounded(px(8.))
                .bg(gpui::rgb(0xffffff))
                .shadow(vec![gpui::BoxShadow {
                    color: gpui::hsla(250. / 360., 0.9, 0.7, 0.45),
                    offset: gpui::point(px(0.), px(0.)),
                    blur_radius: px(14.),
                    spread_radius: px(0.),
                    inset: false,
                }])
                .cursor_pointer()
                .flex()
                .items_center()
                .gap(px(4.))
                .child(
                    gpui::svg()
                        .path("icons/boost_gem.svg")
                        .size(px(20.))
                        .text_color(gpui::rgb(0x000000)),
                )
                .child(
                    div()
                        .text_size(px(16.))
                        .line_height(px(20.))
                        .font_weight(FontWeight(500.))
                        .text_color(gpui::rgb(0x000000))
                        .child("Unlock with Boosting"),
                )
                .on_click(cx.listener(|this, _, _, cx| {
                    this.open_perks(super::server_boost::Perks::Vanity, cx);
                }))
                .into_any_element()
        };
        div()
            .flex()
            .flex_col()
            .child(
                div()
                    .mb(px(24.))
                    .text_size(px(20.))
                    .line_height(px(24.))
                    .font_weight(FontWeight(600.))
                    .text_color(color("--text-strong"))
                    .child("Server Tag"),
            )
            .child(
                div()
                    .flex()
                    .child(
                        div()
                            .w(px(332.))
                            .flex_none()
                            .mr(px(40.))
                            .child(
                                div()
                                    .mb(px(24.))
                                    .child(
                                        div()
                                            .text_size(px(14.))
                                            .line_height(px(18.))
                                            .font_weight(FontWeight(500.))
                                            .text_color(color("--text-subtle"))
                                            .child(description),
                                    )
                                    .when(!public, |this| {
                                        this.child(
                                            div().mt(px(16.)).child(Self::tag_notice(edit_setting)),
                                        )
                                    }),
                            )
                            .child(div().mb(px(8.)).child(top_control))
                            .child(self.tag_form(guild, enabled, cx))
                            .children(error.map(|error| {
                                div()
                                    .mt(px(12.))
                                    .text_size(px(14.))
                                    .line_height(px(18.))
                                    .text_color(color("--text-feedback-critical"))
                                    .child(error)
                            })),
                    )
                    .child(self.tag_preview()),
            )
            .into_any_element()
    }
