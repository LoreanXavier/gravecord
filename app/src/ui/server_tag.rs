    pub(super) fn request_tag(&mut self, guild: Id) {
        use base64::Engine;
        for (index, svg) in BADGE_SVGS.iter().enumerate() {
            let image = self
                .images
                .entry(format!("tag-badge:{index}"))
                .or_insert_with(|| {
                    Arc::new(Image::from_bytes(ImageFormat::Svg, svg.as_bytes().to_vec()))
                })
                .clone();
            if index < BADGE_IDS.len() {
                self.images
                    .entry(format!("tag-badge-id:{}", BADGE_IDS[index]))
                    .or_insert(image);
            } else if index < VISIBLE_BADGES + LOCKED_BADGES {
                let pets_id = 21 + (index - VISIBLE_BADGES) as u64;
                self.images
                    .entry(format!("tag-badge-id:{pets_id}"))
                    .or_insert(image);
            }
        }
        for &(badge_id, svg) in EXTRA_LOCKED_BADGES {
            self.images
                .entry(format!("tag-badge-id:{badge_id}"))
                .or_insert_with(|| {
                    Arc::new(Image::from_bytes(ImageFormat::Svg, svg.as_bytes().to_vec()))
                });
        }
        for (index, avatar) in PREVIEW_AVATARS.iter().enumerate() {
            if let Ok(bytes) = base64::engine::general_purpose::STANDARD.decode(avatar) {
                self.images
                    .entry(format!("tag-avatar:{index}"))
                    .or_insert_with(|| Arc::new(Image::from_bytes(ImageFormat::Png, bytes)));
            }
        }
        let _ = self.requests.send(Request::Rest {
            key: Some(format!("{TAG_PREFIX}{guild}")),
            method: reqwest::Method::GET,
            route: format!("/guilds/{guild}/profile"),
            body: None,
        });
    }

    pub(super) fn tag_fetched(&mut self, key: &str, cx: &mut Context<Self>) {
        let report = self.fetched.get(key).cloned().unwrap_or_default();
        if let Some(guild) = key.strip_prefix(SAVED_PREFIX) {
            if report["ok"] == true {
                if let Ok(guild) = guild.parse::<Id>() {
                    self.request_tag(guild);
                }
            } else if let Some(state) = self.tag_mut() {
                state.error = report["body"]["message"].as_str().map(str::to_owned);
            }
            cx.notify();
            return;
        }
        if report["ok"] != true {
            return;
        }
        let body = &report["body"];
        let text = |name: &str| body[name].as_str().map(str::to_owned);
        let values = TagValues {
            tag: text("tag"),
            badge: body["badge"].as_u64().unwrap_or(BADGE_IDS[0]),
            primary: text("badge_color_primary"),
            secondary: text("badge_color_secondary"),
        };
        let shown = values.tag.clone().unwrap_or_default();
        let field = cx.new(|cx| {
            let mut editor = Editor::new(super::editor_style(), cx);
            editor.set_placeholder("WUMP".to_owned());
            editor.set_text(&shown);
            editor
        });
        let events = cx.subscribe(&field, |this, editor, event: &EditorEvent, cx| {
            match event {
                EditorEvent::Submit(text) => {
                    let text = text.clone();
                    editor.update(cx, |editor, _| editor.set_text(&text));
                }
                EditorEvent::Edited => {
                    let text = editor.read(cx).text().to_owned();
                    let kept = clean_tag(&text);
                    if kept != text {
                        editor.update(cx, |editor, _| editor.set_text(&kept));
                    }
                    if let Some(state) = this.tag_mut() {
                        state.now.tag = Some(kept);
                    }
                }
                EditorEvent::Cancel => {}
            }
            cx.notify();
        });
        let visibility = body["visibility"].as_u64().unwrap_or(0);
        if let Some(state) = self.tag_mut() {
            state.saved = values.clone();
            state.now = values;
            state.visibility = visibility;
            state.field = Some((field, events));
            state.error = None;
        }
        cx.notify();
    }

    pub(super) fn tag_dirty(&self) -> bool {
        self.server_settings
            .as_ref()
            .is_some_and(|open| open.tag.saved != open.tag.now)
    }

    pub(super) fn reset_tag(&mut self, cx: &mut Context<Self>) {
        let mut field = None;
        if let Some(state) = self.tag_mut() {
            state.now = state.saved.clone();
            state.error = None;
            field = state
                .field
                .as_ref()
                .map(|(editor, _)| (editor.clone(), state.saved.tag.clone().unwrap_or_default()));
        }
        if let Some((editor, text)) = field {
            editor.update(cx, |editor, _| editor.set_text(&text));
        }
        cx.notify();
    }

    pub(super) fn save_tag(&mut self, guild: Id, cx: &mut Context<Self>) {
        let Some(state) = self.server_settings.as_ref().map(|open| &open.tag) else {
            return;
        };
        let body = tag_body(&state.now);
        let _ = self.requests.send(Request::Rest {
            key: Some(format!("{SAVED_PREFIX}{guild}")),
            method: reqwest::Method::PATCH,
            route: format!("/guilds/{guild}/profile"),
            body: Some(body),
        });
        cx.notify();
    }

    fn go_to_page(&mut self, page: super::server_settings::Page, cx: &mut Context<Self>) {
        if let Some(open) = self.server_settings.as_mut() {
            open.page = page;
        }
        if let Some(guild) = self.server_settings.as_ref().map(|open| open.guild) {
            self.request_server_page(guild, page, cx);
        }
        cx.notify();
    }

