/// The tag's values, as saved and as edited.
#[derive(Clone, Debug, Default, PartialEq)]
pub(crate) struct TagValues {
    tag: Option<String>,
    badge: u64,
    primary: Option<String>,
    secondary: Option<String>,
}

/// `NR`'s filter: what the input keeps of what was typed.
fn clean_tag(text: &str) -> String {
    text.chars()
        .filter(char::is_ascii_alphanumeric)
        .take(TAG_LIMIT)
        .collect()
}

/// `NJ`'s body.
fn tag_body(values: &TagValues) -> Value {
    json!({
        "tag": values.tag,
        "badge": values.badge,
        "badge_color_primary": values.primary,
        "badge_color_secondary": values.secondary,
    })
}

