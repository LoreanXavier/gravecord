//! `cargo xtask report`: regenerates the status block of `PARITY.md` and keeps its session log.

use anyhow::{Context, Result};
use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::fs;
use std::path::Path;
use std::process::Command;

const LOG_HEADING: &str = "## Session log";

fn status_counts(features: &str) -> BTreeMap<(String, String), usize> {
    let mut counts = BTreeMap::new();
    for line in features.lines().filter(|line| line.starts_with("| F-")) {
        let cells: Vec<&str> = line.split('|').map(str::trim).collect();
        if let (Some(area), Some(status)) = (cells.get(2), cells.get(5)) {
            *counts
                .entry(((*area).to_owned(), (*status).to_owned()))
                .or_insert(0) += 1;
        }
    }
    counts
}

fn table(counts: &BTreeMap<(String, String), usize>) -> String {
    let mut out =
        String::from("| area | todo | wip | done | blocked-substitute |\n| - | - | - | - | - |\n");
    let areas: Vec<&String> = {
        let mut areas: Vec<&String> = counts.keys().map(|(area, _)| area).collect();
        areas.dedup();
        areas
    };
    for area in areas {
        let count = |status: &str| {
            counts
                .get(&(area.clone(), status.to_owned()))
                .copied()
                .unwrap_or(0)
        };
        let _ = writeln!(
            out,
            "| {area} | {} | {} | {} | {} |",
            count("todo"),
            count("wip"),
            count("done"),
            count("blocked-substitute")
        );
    }
    out
}

fn build_line(build: &str, key: &str) -> String {
    build
        .lines()
        .find_map(|line| line.strip_prefix(key)?.strip_prefix('='))
        .unwrap_or("unknown")
        .to_owned()
}

pub fn run(repo: &Path) -> Result<()> {
    let features = fs::read_to_string(repo.join("FEATURES.md"))?;
    let build =
        fs::read_to_string(repo.join("design/snapshot/BUILD")).context("no pinned BUILD")?;
    let blocked = fs::read_to_string(repo.join("BLOCKED.md"))?;
    let parity = fs::read_to_string(repo.join("PARITY.md"))?;
    let commit = Command::new("git")
        .args(["rev-parse", "--short", "HEAD"])
        .current_dir(repo)
        .output()?;
    let log = parity
        .find(LOG_HEADING)
        .map_or_else(|| format!("{LOG_HEADING}\n"), |at| parity[at..].to_owned());

    let counts = status_counts(&features);
    let total: usize = counts.values().sum();
    let mut out = String::from(
        "# PARITY.md\n\nGenerated by `cargo xtask report`. The session log below is kept.\n\n",
    );
    let _ = writeln!(
        out,
        "- Commit: `{}`",
        String::from_utf8_lossy(&commit.stdout).trim()
    );
    let _ = writeln!(
        out,
        "- Pinned build: desktop {}, web {}",
        build_line(&build, "desktop_version"),
        build_line(&build, "client_build_number")
    );
    let _ = writeln!(out, "- Features: {total} rows");
    let _ = writeln!(
        out,
        "- Documented gaps in `BLOCKED.md`: {}",
        blocked.matches("\n### ").count()
    );
    out.push_str("- Parity: no screen is green. `cargo xtask parity` measures a pixel diff only; the layout-tree diff is not built.\n\n");
    out.push_str(&table(&counts));
    out.push('\n');
    out.push_str(&log);
    fs::write(repo.join("PARITY.md"), out)?;
    println!("PARITY.md regenerated, {total} rows");
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    const FEATURES: &str = "| F-0001 | store | a | X:1 | todo | | |\n| F-0002 | store | b | X:2 | wip | | |\n| F-0003 | route | c | X:3 | todo | | |\n";

    #[test]
    fn counts_rows_by_area_and_status() {
        let counts = status_counts(FEATURES);
        assert_eq!(counts[&("store".to_owned(), "wip".to_owned())], 1);
        assert_eq!(counts.values().sum::<usize>(), 3);
    }

    #[test]
    fn table_has_one_line_per_area() {
        let text = table(&status_counts(FEATURES));
        assert!(text.contains("| route | 1 | 0 | 0 | 0 |"));
        assert!(text.contains("| store | 1 | 1 | 0 | 0 |"));
    }

    #[test]
    fn reads_build_fields() {
        assert_eq!(
            build_line("a=1\nclient_build_number=667580\n", "client_build_number"),
            "667580"
        );
        assert_eq!(build_line("", "x"), "unknown");
    }
}
