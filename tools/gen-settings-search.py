"""Generate app/src/ui/settings/search_terms.rs: the keywords the official settings search matches besides titles.

python tools/gen-settings-search.py

Module 122088 matches the query as a subsequence of a node's title and of every string its `useSearchTerms` returns.
Those lists live in the settings modules (158935, 172471, 569386, ...); each is keyed by the node's anchor key (module
780964 `X`). Strings come from design/snapshot/dumps/STRINGS/en-US.json.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MODULES = ROOT / 'design' / 'snapshot' / 'modules'
OUT = ROOT / 'app' / 'src' / 'ui' / 'settings' / 'search_terms.rs'

strings = json.load(open(ROOT / 'design' / 'snapshot' / 'dumps' / 'STRINGS' / 'en-US.json', encoding='utf8'))
enum = open(MODULES / '780964.js', encoding='utf8').read()
names = dict(re.findall(r'\w\.([A-Z0-9_]+)="([a-z0-9_]+)"', enum))


def text_of(entry):
    if entry is None:
        return None
    return ''.join(part for part in entry if isinstance(part, str))


def terms_in(body):
    out = []
    for m in re.finditer(r'"([^"]*)"|\w\.intl\.string\(\w\.t(?:\.([A-Za-z0-9_]+)|\["([^"]+)"\])\)', body):
        if m.group(1) is not None:
            out.append(m.group(1))
        else:
            ident = m.group(2) or m.group(3)
            text = text_of(strings.get(ident))
            if text:
                out.append(text)
    return out


found = {}
for path in MODULES.glob('*.js'):
    source = path.read_text(encoding='utf8', errors='ignore')
    if 'useSearchTerms' not in source:
        continue
    for m in re.finditer(r'useSearchTerms:\(\)=>\[', source):
        depth, i = 1, m.end()
        while depth and i < len(source):
            depth += {'[': 1, ']': -1}.get(source[i], 0)
            i += 1
        body = source[m.end():i - 1]
        before = source[max(0, m.start() - 4000):m.start()]
        owner = list(re.finditer(r'\w\.X\.([A-Z0-9_]+),\{', before))
        # The props may come before or after the key: look back first, then forward.
        owner_name = owner[-1].group(1) if owner else None
        after = source[i:i + 200]
        if owner_name is None or (owner and len(before) - owner[-1].end() > 3500):
            continue
        key = names.get(owner_name)
        if key:
            found.setdefault(key, [])
            for term in terms_in(body):
                if term not in found[key]:
                    found[key].append(term)

lines = ['//! Generated by `tools/gen-settings-search.py` from the settings modules. Do not edit by hand.',
         '//! The extra strings the official settings search matches (`useSearchTerms`, module 122088), by anchor key.',
         '',
         'pub(in crate::ui) const TERMS: &[(&str, &[&str])] = &[']
for key in sorted(found):
    terms = ', '.join(json.dumps(t, ensure_ascii=False) for t in found[key])
    lines.append(f'    ({json.dumps(key)}, &[{terms}]),')
lines.append('];')
OUT.write_text('\n'.join(lines) + '\n', encoding='utf8')
print(len(found), 'keys')
