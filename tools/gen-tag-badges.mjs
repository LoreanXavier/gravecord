// node tools/gen-tag-badges.mjs  Reads the Server Tag page in the clean client (it must be open) and writes
// app/src/ui/tag_badges.rs: every badge and colour swatch as the SVG the page draws, in the page's order. Colours stay as
// {primary} and {secondary}, so a chosen pair can be filled in.
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { connect } from './cdp.mjs';
import { PRELUDE } from './webpack.mjs';

const page = await connect();
const raw = JSON.parse(await page.evaluate(`(async () => { ${PRELUDE}
  const items = [...document.querySelectorAll('[class*=pickerItem_]')];
  const svgs = items.map((item) => {
    const svg = item.querySelector('svg');
    return svg ? svg.outerHTML : null;
  });
  const avatars = [...document.querySelectorAll('[class*=avatar_YRgiYF]')].map((image) => image.src);
  const colours = req(743981);
  const names = [...document.querySelectorAll('[class*=usernameContainer_YRgiYF] > div:first-child')].map((node) => getComputedStyle(node).color);
  return JSON.stringify({ svgs, avatars, names, pairs: colours.Ub, badges: Object.keys(colours.hc ?? {}), defaults: colours.hc });
})()`));
const module = await page.evaluate(`(async () => { ${PRELUDE}
  const found = {};
  for (const id of Object.keys(webpackRequire?.m ?? {})) { found[id] = 1; }
  return Object.keys(found).length;
})()`).catch(() => 0);
const all = raw.svgs.filter(Boolean);
// The first 15 are badges (10 unlocked in view and 5 under the fold of Show all), the rest the colour pairs.
const clean = (svg) => svg
  .replace(/ class="[^"]*"/g, '')
  .replace(/ aria-[a-z]+="[^"]*"/g, '')
  .replace(/ role="[^"]*"/g, '');
const lines = [
  '//! The Server Tag page\'s badges and colour swatches as it draws them. Generated by `tools/gen-tag-badges.mjs` from the',
  '//! clean client; do not edit.',
  '',
  `pub(super) const BADGE_SVGS: &[&str] = &[`,
];
const hashes = (text) => {
  let marks = '#';
  while (text.includes(`"${marks}`)) marks += '#';
  return marks;
};
for (const svg of all) {
  const text = clean(svg);
  const marks = hashes(text);
  lines.push(`    r${marks}"${text}"${marks},`);
}
lines.push('];', '');
lines.push('/// The preview\'s people, as the bundle embeds them.', 'pub(super) const PREVIEW_AVATARS: &[&str] = &[');
for (const avatar of raw.avatars) lines.push(`    "${avatar.replace(/^data:image\/png;base64,/, '')}",`);
lines.push('];', '');
lines.push('/// `NL.Ub`: the preset colour pairs, primary then secondary.', 'pub(super) const COLOR_PAIRS: &[(&str, &str)] = &[');
for (const pair of raw.pairs) lines.push(`    (${JSON.stringify(pair.primary)}, ${JSON.stringify(pair.secondary)}),`);
lines.push('];', '');
lines.push('/// `NL.hc`: badge ids, in the picker\'s order.', 'pub(super) const BADGE_IDS: &[u64] = &[');
for (const badge of Object.values(raw.defaults ?? {})) lines.push(`    ${Number(badge)},`);
lines.push('];', '');
console.log(JSON.stringify(raw.names));
const path = join(import.meta.dirname, '..', 'app', 'src', 'ui', 'tag_badges.rs');
writeFileSync(path, lines.join('\n'));
console.log(path, all.length, 'items', module);
process.exit(0);
