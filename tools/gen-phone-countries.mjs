// Writes app/src/ui/settings/phone_countries.rs: the options of the "Country Code" select of the Add phone dialog.
// Module 96337 lists the countries and their dialing codes; module 956956 `Gw` names a country by its alpha-2 code
// (the en-US string the intl message hash points at). One option per (alpha2, code) pair, in the module's order:
// `${alpha2}-${code}` is the option's value in module 938401.
import { readFileSync, writeFileSync } from 'node:fs';

const snap = new URL('../design/snapshot/', import.meta.url);
const read = (p) => readFileSync(new URL(p, snap), 'utf8');
const strings = JSON.parse(read('dumps/STRINGS/en-US.json'));
const names = read('modules/956956.js');
const countries = read('modules/96337.js');

// `KG:()=>d.intl.string(d.t.E312FJ)` and `KZ:()=>d.intl.string(d.t["PwbVJ/"])`.
const hashOf = new Map();
for (const m of names.matchAll(/\b([A-Z]{2}):\(\)=>d\.intl\.string\(d\.t(?:\.([\w$]+)|\["([^"]+)"\])\)/g)) {
  hashOf.set(m[1], m[2] ?? m[3]);
}

const rows = [];
for (const m of countries.matchAll(/\{name:"([^"]*)",alpha2:"([A-Z]{2})",phoneCountryCode:"[^"]*",phoneCountryCodes:\[([^\]]*)\]/g)) {
  const [, moduleName, alpha2, codes] = m;
  const hash = hashOf.get(alpha2);
  const text = hash && strings[hash] ? strings[hash][0] : moduleName;
  if (typeof text !== 'string') throw new Error(`name of ${alpha2} is not plain text`);
  for (const code of codes.match(/"[^"]+"/g).map((c) => c.slice(1, -1))) {
    rows.push({ name: text, alpha2, code });
  }
}

const esc = (s) => s.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
let out = `//! The options of the "Country Code" select of the Add phone dialog (module 938401), generated by
//! \`tools/gen-phone-countries.mjs\` from modules 96337 (countries, dialing codes) and 956956 (\`Gw\`, the names).

/// One option: the country's name, its alpha-2 code (drawn as two regional-indicator letters) and a dialing code.
pub(super) struct Country {
    pub name: &'static str,
    pub alpha2: &'static str,
    pub code: &'static str,
}

pub(super) const COUNTRIES: &[Country] = &[
`;
for (const r of rows) {
  out += `    Country { name: "${esc(r.name)}", alpha2: "${r.alpha2}", code: "${r.code}" },\n`;
}
out += '];\n';
writeFileSync(new URL('../app/src/ui/settings/phone_countries.rs', import.meta.url), out);
console.log(`${rows.length} options, ${hashOf.size} names`);
