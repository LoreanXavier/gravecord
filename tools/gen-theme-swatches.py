"""Generate app/src/ui/settings/swatches.rs: the theme swatches of the Appearance page, from their computed styles.

python tools/gen-theme-swatches.py

Each `themeSelection_IhyaN_` in design/dom/settings/appearance-darker-cozy.json becomes a name, a base color and its
CSS gradient layers (top layer first), so the app can draw the same pictures.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'design' / 'dom' / 'settings' / 'appearance-darker-cozy.json'
OUT = ROOT / 'app' / 'src' / 'ui' / 'settings' / 'swatches.rs'


def split_top(text, separator=','):
    parts, depth, current = [], 0, ''
    for character in text:
        if character == '(':
            depth += 1
        elif character == ')':
            depth -= 1
        if character == separator and depth == 0:
            parts.append(current.strip())
            current = ''
        else:
            current += character
    if current.strip():
        parts.append(current.strip())
    return parts


def color(text):
    numbers = [float(n) for n in re.findall(r'[\d.]+', text)]
    red, green, blue = (round(n) for n in numbers[:3])
    alpha = round((numbers[3] if len(numbers) > 3 else 1.0) * 255)
    return (red << 24) | (green << 16) | (blue << 8) | alpha


def gradient(text):
    inner = text[text.index('(') + 1:text.rindex(')')]
    parts = split_top(inner)
    angle = 180.0
    if parts and re.match(r'^-?[\d.]+deg$', parts[0]):
        angle = float(parts[0][:-3])
        parts = parts[1:]
    elif parts and parts[0].startswith('to '):
        angle = {'to top': 0.0, 'to right': 90.0, 'to bottom': 180.0, 'to left': 270.0}[parts[0]]
        parts = parts[1:]
    stops = []
    for part in parts:
        found = re.match(r'^(rgba?\([^)]*\))\s*([\d.]+%)?$', part)
        stops.append([color(found.group(1)), float(found.group(2)[:-1]) / 100 if found.group(2) else None])
    # Stops without positions are spread evenly between their neighbours, as CSS does.
    if stops[0][1] is None:
        stops[0][1] = 0.0
    if stops[-1][1] is None:
        stops[-1][1] = 1.0
    index = 0
    while index < len(stops):
        if stops[index][1] is None:
            start = index - 1
            end = index
            while stops[end][1] is None:
                end += 1
            for step in range(index, end):
                stops[step][1] = stops[start][1] + (stops[end][1] - stops[start][1]) * (step - start) / (end - start)
            index = end
        index += 1
    return angle, stops


def main():
    capture = json.load(open(SOURCE, encoding='utf8'))
    strings = capture['snapshot']['strings']
    document = capture['snapshot']['documents'][0]
    nodes, layout, names = document['nodes'], document['layout'], capture['computed']
    layout_of = {node: index for index, node in enumerate(layout['nodeIndex'])}
    lines = [
        '//! Generated by `tools/gen-theme-swatches.py` from the Appearance capture. Do not edit by hand.',
        '',
        'use super::model::{Layer, Swatch};',
        '',
        'pub(in crate::ui) const SWATCHES: &[Swatch] = &[',
    ]
    for node, raw in enumerate(nodes['attributes']):
        attrs = {strings[raw[k]]: strings[raw[k + 1]] for k in range(0, len(raw), 2)}
        if 'themeSelection_IhyaN_' not in attrs.get('class', '') or node not in layout_of:
            continue
        style = dict(zip(names, [strings[v] if v >= 0 else '' for v in layout['styles'][layout_of[node]]]))
        base = style.get('background-color', '')
        base_value = color(base) if base.startswith('rgb') and color(base) & 0xff else None
        layers = []
        image = style.get('background-image', 'none')
        if image != 'none':
            for part in split_top(image):
                if part.startswith('linear-gradient'):
                    angle, stops = gradient(part)
                    stop_text = ', '.join(f'(0x{value:08x}, {position:.4f})' for value, position in stops)
                    layers.append(f'Layer {{ angle: {angle:.1f}, stops: &[{stop_text}] }}')
        name = attrs.get('aria-label', '')
        group = 'default' if 'defaultThemeSelect' in attrs.get('class', '') else 'client'
        base_text = f'Some(0x{base_value:08x})' if base_value is not None else 'None'
        lines.append(
            f'    Swatch {{ name: {json.dumps(name)}, group: "{group}", base: {base_text}, layers: &[{", ".join(layers)}] }},'
        )
    lines.append('];')
    OUT.write_text('\n'.join(lines) + '\n', encoding='utf8')
    print(f'{len(lines) - 6} swatches')


main()
