// Resolves every CSS custom property under each theme with a detached probe, so no account setting changes.
// Writes design/tokens/<theme>.json and generates crates/dc-tokens/src/generated.rs (colors only).
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { connect } from './cdp.mjs';

const root = join(import.meta.dirname, '..');
const tokensDir = join(root, 'design', 'tokens');
const bySelector = JSON.parse(readFileSync(join(tokensDir, 'by-selector.json'), 'utf8'));
const names = new Set();
for (const [selector, values] of Object.entries(bySelector)) {
  if (!/(^|[\s,.])(:root|\.theme-|\.visual-refresh)/.test(selector)) continue;
  for (const name of Object.keys(values)) names.add(name);
}
const THEMES = ['dark', 'light', 'darker', 'midnight'];

const page = await connect();
const resolved = JSON.parse(await page.evaluate(`(() => {
  const names = ${JSON.stringify([...names])};
  const themes = ${JSON.stringify(THEMES)};
  const out = {};
  const host = document.createElement('div');
  host.style.cssText = 'position:fixed;left:-9999px;top:-9999px;width:1px;height:1px;visibility:hidden';
  document.body.appendChild(host);
  for (const theme of themes) {
    const scope = document.createElement('div');
    scope.className = 'theme-' + theme + (theme === 'darker' || theme === 'midnight' ? ' theme-dark' : '') + ' images-' + (theme === 'light' ? 'light' : 'dark') + ' visual-refresh';
    const probe = document.createElement('div');
    scope.appendChild(probe);
    host.appendChild(scope);
    const raw = getComputedStyle(probe);
    const colors = {}, values = {};
    for (const name of names) {
      const value = raw.getPropertyValue(name).trim();
      if (!value) continue;
      values[name] = value;
      probe.style.color = '';
      probe.style.color = 'var(' + name + ')';
      const color = getComputedStyle(probe).color;
      if (probe.style.color && !/^var/.test(value.replace(/^\\s+/, '').slice(0, 0))) colors[name] = color;
    }
    out[theme] = { values, colors };
    host.removeChild(scope);
  }
  host.remove();
  return JSON.stringify(out);
})()`));
page.close();

function clamp(c) {
  return Math.round(255 * Math.min(1, Math.max(0, c)));
}
function srgb(c) {
  return c <= 0.0031308 ? 12.92 * c : 1.055 * c ** (1 / 2.4) - 0.055;
}
// Returns [r, g, b, a] in 0..255, or null for anything that is not a plain color.
function parse(color) {
  let match = /^rgba?\(([\d.]+),? ([\d.]+),? ([\d.]+)(?:,? ?\/? ?([\d.]+))?\)$/.exec(color);
  if (match) return [+match[1], +match[2], +match[3], clamp(match[4] === undefined ? 1 : +match[4])].map(Math.round);
  match = /^oklab\(([-\d.e]+) ([-\d.e]+) ([-\d.e]+)(?: \/ ([\d.]+))?\)$/.exec(color);
  if (!match) return null;
  const [L, a, b] = match.slice(1, 4).map(Number);
  const alpha = match[4] === undefined ? 1 : Number(match[4]);
  const l = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3;
  const m = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3;
  const s = (L - 0.0894841775 * a - 1.291485548 * b) ** 3;
  return [
    clamp(srgb(4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s)),
    clamp(srgb(-1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s)),
    clamp(srgb(-0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s)),
    clamp(alpha),
  ];
}

mkdirSync(join(root, 'crates', 'dc-tokens', 'src'), { recursive: true });
const hexOf = (rgba) => rgba.map((c) => c.toString(16).padStart(2, '0')).join('');
const rustName = (name) => name.replace(/^--/, '').replace(/[^a-zA-Z0-9]+/g, '_').toUpperCase();

let tables = '';
for (const theme of THEMES) {
  writeFileSync(join(tokensDir, `${theme}.json`), JSON.stringify(resolved[theme], null, 1));
  const entries = [];
  for (const [name, color] of Object.entries(resolved[theme].colors).sort()) {
    const value = resolved[theme].values[name];
    // A property that is not a color resolves to the inherited text color, so require the raw value to look like one.
    if (!/^(#|rgb|hsl|oklab|color|var\(|color-mix)/.test(value)) continue;
    const rgba = parse(color);
    if (rgba) entries.push(`    (${JSON.stringify(name)}, 0x${hexOf(rgba)}),`);
  }
  tables += `pub const ${theme.toUpperCase()}: &[(&str, u32)] = &[\n${entries.join('\n')}\n];\n\n`;
  console.log(`${theme}: ${Object.keys(resolved[theme].values).length} values, ${entries.length} colors`);
}
writeFileSync(
  join(root, 'crates', 'dc-tokens', 'src', 'generated.rs'),
  `// Generated by tools/dump-tokens.mjs from the pinned build. Do not edit. Values are 0xRRGGBBAA.\n\n${tables}`,
);
void rustName;
