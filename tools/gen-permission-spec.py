"""Generate app/src/ui/permission_spec.rs from the channel permission specs the official client builds.

The specs are dumped by running module 558393's generateChannelPermissionSpec in the clean client for a text channel,
a voice channel and a category, for @everyone and for any other role, into
design/snapshot/TRAFFIC/permission-spec-{text,voice,category}.json.

python tools/gen-permission-spec.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'app' / 'src' / 'ui' / 'permission_spec.rs'


def literal(text):
    if text is None:
        return 'None'
    return 'Some(' + json.dumps(text, ensure_ascii=False) + ')'


def plain(text):
    return json.dumps(text or '', ensure_ascii=False)


def main():
    lines = [
        '//! Channel permission sections, generated by `tools/gen-permission-spec.py` from module 558393\'s',
        '//! `generateChannelPermissionSpec` as the official client builds it. Do not edit by hand.',
        '',
        '/// One permission row: its title, its description (for @everyone where that differs) and its bit.',
        'pub(super) struct Permission {',
        '    pub title: &\'static str,',
        '    pub description: &\'static str,',
        '    pub everyone_description: &\'static str,',
        '    pub flag: u64,',
        '}',
        '',
        'pub(super) struct Section {',
        '    pub title: &\'static str,',
        '    pub description: Option<&\'static str>,',
        '    pub permissions: &\'static [Permission],',
        '}',
        '',
    ]
    for kind in ('text', 'voice', 'category'):
        data = json.loads(open(ROOT / 'design' / 'snapshot' / 'TRAFFIC' / f'permission-spec-{kind}.json', encoding='utf8').read())
        if isinstance(data, str):
            data = json.loads(data)
        lines.append(f'pub(super) static {kind.upper()}: &[Section] = &[')
        for everyone, role in zip(data['everyone'], data['role']):
            lines.append('    Section {')
            lines.append(f'        title: {plain(role["title"])},')
            lines.append(f'        description: {literal(role["description"])},')
            lines.append('        permissions: &[')
            for mine, theirs in zip(role['permissions'], everyone['permissions']):
                lines.append('            Permission {')
                lines.append(f'                title: {plain(mine["title"])},')
                lines.append(f'                description: {plain(mine["description"])},')
                lines.append(f'                everyone_description: {plain(theirs["description"])},')
                lines.append(f'                flag: {int(mine["flag"])},')
                lines.append('            },')
            lines.append('        ],')
            lines.append('    },')
        lines.append('];')
        lines.append('')
    # The role editor's list (module 558393 `generateGuildPermissionSpec`), dumped to permission-spec-guild.json.
    guild = json.loads(open(ROOT / 'design' / 'snapshot' / 'TRAFFIC' / 'permission-spec-guild.json', encoding='utf8').read())
    lines.append('pub(super) static GUILD: &[Section] = &[')
    for section in guild:
        lines.append('    Section {')
        lines.append(f'        title: {plain(section["title"])},')
        lines.append(f'        description: {literal(section["description"])},')
        lines.append('        permissions: &[')
        for permission in section['permissions']:
            lines.append('            Permission {')
            lines.append(f'                title: {plain(permission["title"])},')
            lines.append(f'                description: {plain(permission["description"])},')
            lines.append(f'                everyone_description: {plain(permission["description"])},')
            lines.append(f'                flag: {int(permission["flag"])},')
            lines.append('            },')
        lines.append('        ],')
        lines.append('    },')
    lines.append('];')
    lines.append('')
    OUT.write_text('\n'.join(lines), encoding='utf8')
    print(OUT)


main()
