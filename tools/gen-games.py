"""Generate app/src/ui/games_spec.rs from the pinned bundle.

- POPULAR: module 282435 `sx`, the games Server Profile offers before anything is typed. `jN` ranks them by their
  distance from the end of the list, so the first is the most popular.
- EXCLUDED: module 926675's set, ids that game search and pickers never show (`qS`, `XX` in modules 929396, 735321).

python tools/gen-games.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MODULES = ROOT / 'design' / 'snapshot' / 'modules'
OUT = ROOT / 'app' / 'src' / 'ui' / 'games_spec.rs'


def ids_after(source, marker):
    start = source.index(marker) + len(marker)
    end = source.index(']', start)
    return json.loads('[' + source[start:end] + ']')


def main():
    popular = ids_after((MODULES / '282435.js').read_text(encoding='utf8'), 'let i=[')
    excluded_source = (MODULES / '926675.js').read_text(encoding='utf8')
    excluded = ids_after(excluded_source, 'new Set([')
    assert all(re.fullmatch(r'\d+', id) for id in popular + excluded)
    lines = [
        '//! Game id lists, generated by `tools/gen-games.py` from modules 282435 and 926675. Do not edit by hand.',
        '',
        '/// Module 282435 `sx`: the games offered before a search, most popular first.',
        'pub(super) const POPULAR: &[&str] = &[',
    ]
    lines += [f'    "{id}",' for id in popular]
    lines += [
        '];',
        '',
        '/// Module 926675: ids game search never shows.',
        'pub(super) const EXCLUDED: &[&str] = &[',
    ]
    lines += [f'    "{id}",' for id in excluded]
    lines += ['];', '']
    OUT.write_text('\n'.join(lines), encoding='utf8', newline='\n')
    print(f'{len(popular)} popular, {len(excluded)} excluded -> {OUT}')


if __name__ == '__main__':
    main()
