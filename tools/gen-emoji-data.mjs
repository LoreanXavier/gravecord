// Generates crates/dc-tokens/src/emoji_data.rs from the pinned emoji dataset (module 13474, the client's emojis.json):
// every unicode emoji with its names, surrogates, sprite index and diversity children, the category ranges, and a
// sorted name index for lookups.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dirname, '..');
const source = readFileSync(join(root, 'design', 'snapshot', 'modules', '13474.js'), 'utf8');
const literal = source.match(/JSON\.parse\('([\s\S]*)'\)/)[1];
// The module embeds the JSON as a single-quoted JS string literal; decode its escapes exactly as JS would.
const data = JSON.parse(Function(`return '${literal}'`)());

const rust = (text) => JSON.stringify(text).replace(/\\u([0-9a-fA-F]{4})/g, (_, hex) => `\\u{${hex}}`);
const rows = data.emojis.map((emoji) => {
  const names = `&[${emoji.names.map(rust).join(', ')}]`;
  const sprite = emoji.spriteIndex == null ? 'None' : `Some(${emoji.spriteIndex})`;
  const children = `&[${(emoji.diversityChildren ?? []).join(', ')}]`;
  const diversity = emoji.diversity ? `&[${emoji.diversity.map(rust).join(', ')}]` : '&[]';
  return `    Emoji { names: ${names}, surrogates: ${rust(emoji.surrogates)}, sprite: ${sprite}, has_diversity: ${!!emoji.hasDiversity}, diversity_children: ${children}, diversity: ${diversity} },`;
});
const categories = Object.entries(data.emojisByCategory)
  .map(([name, [start, end]]) => `    (${rust(name)}, ${start}, ${end}),`)
  .join('\n');
const names = Object.entries(data.nameToEmoji).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
const index = names.map(([name, at]) => `    (${rust(name)}, ${at}),`).join('\n');

writeFileSync(
  join(root, 'crates', 'dc-tokens', 'src', 'emoji_data.rs'),
  `// Generated by tools/gen-emoji-data.mjs from the pinned build (module 13474). Do not edit.

pub struct Emoji {
    pub names: &'static [&'static str],
    pub surrogates: &'static str,
    pub sprite: Option<u16>,
    pub has_diversity: bool,
    /// Indexes of the skin tone variants, in tone order.
    pub diversity_children: &'static [u16],
    /// For a variant, the tone modifiers it carries.
    pub diversity: &'static [&'static str],
}

pub const EMOJIS: &[Emoji] = &[
${rows.join('\n')}
];

/// Picker categories in order, as half-open ranges of \`EMOJIS\` (diversity variants come after the last).
pub const CATEGORIES: &[(&str, u16, u16)] = &[
${categories}
];

/// Every name and alias, sorted, with the emoji's index.
pub const NAMES: &[(&str, u16)] = &[
${index}
];
`,
);
console.log(`${data.emojis.length} emoji, ${names.length} names`);
