// Generates crates/dc-tokens/src/emoji.rs: unicode emoji codepoints to their pinned asset file, from module 874629.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dirname, '..');
const snapshot = join(root, 'design', 'snapshot');
const map = readFileSync(join(snapshot, 'modules', '874629.js'), 'utf8');
const images = JSON.parse(readFileSync(join(snapshot, 'dumps', 'IMAGES.md'), 'utf8'));

const entries = [];
for (const [, codepoints, module] of map.matchAll(/"\.\/([0-9a-f-]+)\.svg":"?(\d+)"?/g)) {
  const file = images[module];
  if (file) entries.push([codepoints, file]);
}
entries.sort(([a], [b]) => (a < b ? -1 : 1));
const body = entries.map(([codepoints, file]) => `    (${JSON.stringify(codepoints)}, ${JSON.stringify(file)}),`).join('\n');
writeFileSync(
  join(root, 'crates', 'dc-tokens', 'src', 'emoji.rs'),
  `// Generated by tools/gen-emoji.mjs from the pinned build. Do not edit.\n\npub const EMOJI_FILES: &[(&str, &str)] = &[\n${body}\n];\n`,
);
console.log(`${entries.length} emoji`);
