// node tools/gen-confusables.mjs
// Module 209034 (the skeleton table behind `S8` in module 23339) into crates/dc-state/src/confusables.rs.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dirname, '..');
const source = readFileSync(join(root, 'design/snapshot/modules/209034.js'), 'utf8');
const literal = source.match(/JSON\.parse\('([\s\S]*)'\)/)[1];
const table = JSON.parse(new Function(`return '${literal}'`)());
const escape = (text) => [...text].map((c) => `\\u{${c.codePointAt(0).toString(16)}}`).join('');
const rows = Object.keys(table)
  .map((key) => [key.codePointAt(0), table[key]])
  .sort((a, b) => a[0] - b[0]);
const lines = [
  '// Generated by tools/gen-confusables.mjs from the pinned build (module 209034). Do not edit.',
  '',
  '/// Each character with the skeleton `S8` replaces it by, sorted by character.',
  'pub const SKELETON: &[(char, &str)] = &[',
  ...rows.map(([code, value]) => `    ('\\u{${code.toString(16)}}', "${escape(value)}"),`),
  '];',
  '',
];
writeFileSync(join(root, 'crates/dc-state/src/confusables.rs'), lines.join('\n'));
console.log(`${rows.length} entries`);
