"""Writes app/src/ui/game_genres.rs: the game genre ids (module 346699) with their English names (module 541830 `du`).

python tools/gen-game-genres.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MODULES = ROOT / "design" / "snapshot" / "modules"
STRINGS = json.loads((ROOT / "design" / "snapshot" / "dumps" / "STRINGS" / "en-US.json").read_text(encoding="utf-8"))


def text(key):
    value = STRINGS[key]
    return "".join(part for part in value if isinstance(part, str)) if isinstance(value, list) else str(value)


enum = (MODULES / "346699.js").read_text(encoding="utf-8")
ids = {name: int(number) for name, number in re.findall(r'\[i\.([A-Z_]+)=(\d+)\]', enum)}
names = (MODULES / "541830.js").read_text(encoding="utf-8")
cases = re.findall(r'case A\.dHA\.([A-Z_]+):return l\.intl\.string\(l\.t(?:\.([A-Za-z0-9_$]+)|\["([^"]+)"\])\)', names)
rows = []
for name, key_dot, key_bracket in cases:
    key = key_dot or key_bracket
    if name in ids:
        rows.append((ids[name], text(key)))
rows.sort()
out = [
    "//! Generated by `tools/gen-game-genres.py` from modules 346699 (the genre ids) and 541830 (`du`, their names).",
    "",
    "/// A game genre id and its English name.",
    "pub(super) const GENRES: &[(u64, &str)] = &[",
]
out += [f"    ({number}, {json.dumps(label, ensure_ascii=False)})," for number, label in rows]
out += ["];", "", "/// The name of a genre id, as module 541830 `du` gives it.", "pub(super) fn genre_name(id: u64) -> Option<&'static str> {",
        "    GENRES.iter().find(|(known, _)| *known == id).map(|(_, name)| *name)", "}", ""]
(ROOT / "app" / "src" / "ui" / "game_genres.rs").write_text("\n".join(out), encoding="utf-8")
print(len(rows), "genres")
